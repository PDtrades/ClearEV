import { chromium, devices } from "@playwright/test";
const out = process.argv[2] ?? "/mnt/project-files/clearev/demo";
const base = "http://127.0.0.1:3100";
const gl = ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"];
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM, args: gl });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1, recordVideo: { dir: out + "/video-raw", size: { width: 1440, height: 900 } } });
const page = await ctx.newPage();
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` });
const settle = async (ms = 4500) => page.waitForTimeout(ms);
const FROM = process.argv[3] ?? "start";
if (FROM === "start") {
await page.goto(base + "/", { waitUntil: "networkidle" });
await page.locator(".maplibregl-marker").nth(51).waitFor();
await settle(6000);
await shot("01-home-3d-map");
// hover a state for the summary popup
const box = await page.locator(".maplibregl-canvas").boundingBox();
await page.mouse.move(box.x + box.width * 0.42, box.y + box.height * 0.45);
await settle(2500);
await shot("02-hover-state");
await page.mouse.click(box.x + box.width * 0.42, box.y + box.height * 0.45);
await settle(3500);
await shot("03-state-selected");
await page.getByLabel("ZIP code").fill("94110");
await page.getByRole("button", { name: "Search" }).click();
await page.getByRole("heading", { name: /Programs for ZIP 94110/ }).waitFor();
await settle(5000);
await shot("04-zip-search");
await page.locator("summary", { hasText: "Household details" }).click();
await page.getByLabel("Household annual income (USD)").fill("160000");
await page.getByLabel("Tax filing status").selectOption("single");
await page.getByRole("list", { name: "Program results" }).getByText(/Appears ineligible/).first().waitFor();
await settle(1500);
await page.getByRole("list", { name: "Program results" }).first().scrollIntoViewIfNeeded();
await shot("05-income-verdicts");
await page.getByRole("checkbox", { name: /^Solar$/ }).check();
await settle(1500);
await shot("06-solar-filter");
await page.getByRole("button", { name: "Clear filters" }).click();
await settle(1000);
const card = page.getByRole("list", { name: "Program results" }).getByRole("listitem").first().locator("article");
await card.scrollIntoViewIfNeeded();
await card.click();
await settle(1200);
await shot("07-selected-result");
await page.goto(base + "/program/federal_curated:irs-25e", { waitUntil: "networkidle" });
await settle(800);
await page.screenshot({ path: `${out}/08-program-detail.png`, fullPage: true });
await page.goto(base + "/coverage", { waitUntil: "networkidle" });
await settle(800);
await page.screenshot({ path: `${out}/09-coverage.png`, fullPage: true });
}
// admin
await page.goto(base + "/admin/login", { waitUntil: "networkidle" });
await page.getByLabel("Password").fill("demo-password-2026");
await page.getByRole("button", { name: "Sign in" }).click();
await page.getByRole("heading", { name: "Ingestion health" }).waitFor();
await settle(800);
await shot("10-admin-dashboard");
await page.goto(base + "/admin/runs", { waitUntil: "networkidle" });
await settle(600);
await shot("11-admin-runs");
await page.goto(base + "/admin/review", { waitUntil: "networkidle" });
await settle(600);
await shot("12-admin-review");
await page.close();
await ctx.close();
// mobile
const m = await browser.newContext({ ...devices["Pixel 7"] });
const mp = await m.newPage();
await mp.goto(base + "/?zip=10001", { waitUntil: "networkidle" });
await mp.waitForTimeout(1500);
await mp.screenshot({ path: `${out}/13-mobile-list.png` });
await mp.getByRole("button", { name: "Map", exact: true }).click();
await mp.waitForTimeout(7000);
await mp.screenshot({ path: `${out}/14-mobile-map.png` });
await m.close();
// no WebGL fallback
const nb = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM, args: ["--disable-gpu", "--disable-webgl", "--disable-3d-apis"] });
const np = await nb.newPage({ viewport: { width: 1440, height: 900 } });
await np.goto(base + "/?state=CO", { waitUntil: "networkidle" });
await np.waitForTimeout(1500);
await np.screenshot({ path: `${out}/15-no-webgl-fallback.png` });
await nb.close();
await browser.close();
